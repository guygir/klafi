const bits = (modules) => modules.map((row) => row.map((dark) => (dark ? "1" : "0")).join(""));

test("league QR matrices match a reference encoder (format cells don't steal data modules)", () => {
  assert.deepEqual(bits(qrModules("HELLO")), HELLO_V1);
  assert.deepEqual(bits(qrModules("https://klafi.vercel.app/?league=ABC234")), JOIN_URL_V3);
});

test("league QR SVG keeps a 4-module quiet zone", () => {
  const svg = qrSvg("https://klafi.vercel.app/?league=ABC234");
  assert.match(svg, /viewBox="0 0 37 37"/);
  assert.doesNotMatch(svg, /<rect x="[0-3]" /);
});
